// Builds members/basilica-info.js — each basilica's year of designation, three facts and Wikipedia link —
// from the MARKERS data inside index.html, so the members' page for each basilica (basilica.html) shows the
// same facts as the main map's popup without loading the whole map page.
// Run from the repo root after changing the facts in index.html:   node tools/build_basilica_info.mjs
import fs from "node:fs";

const line = fs.readFileSync("index.html", "utf8").split("\n").find((l) => l.startsWith("const MARKERS = "));
if (!line) throw new Error("MARKERS not found in index.html");
const MARKERS = JSON.parse(line.replace(/^const MARKERS = /, "").replace(/;\s*$/, ""));
const info = {};
for (const m of MARKERS) {
  if (!m.ph) continue;
  info[m.ph] = { yr: m.yr || null, f: [m.f1, m.f2, m.f3].filter(Boolean), wu: m.wu || null };
}
const out = "/* Generated by tools/build_basilica_info.mjs from the map data in index.html. Do not edit by hand. */\n" +
  "window.AB_INFO = " + JSON.stringify(info) + ";\n";
fs.writeFileSync("members/basilica-info.js", out);
console.log("members/basilica-info.js:", Object.keys(info).length, "basilicas,", out.length, "bytes");
