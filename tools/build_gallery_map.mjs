// Builds members/gallery-map.js — the members' gallery map — from the map data inside index.html,
// so the gallery map matches the main map exactly (same projection, outlines, lakes and marker positions)
// without the gallery page having to load d3 or the full map.
// Run from the repo root after changing the map data:   node tools/build_gallery_map.mjs
import fs from "node:fs";
import vm from "node:vm";

const html = fs.readFileSync("index.html", "utf8");
const lines = html.split("\n");
const find = (re) => { const i = lines.findIndex((l) => re.test(l)); if (i < 0) throw new Error("not found: " + re); return i; };

const ctx = vm.createContext({});
vm.runInContext(lines[find(/^!function\(t,n\)\{"object"==typeof exports/)], ctx);       // the inlined d3 bundle
const g0 = find(/^const GEO_TOPO = /), g1 = find(/^\}\)\(GEO_TOPO\);/);
vm.runInContext(lines.slice(g0, g1 + 1).join("\n"), ctx);
vm.runInContext(lines[find(/^const MARKERS = /)], ctx);
vm.runInContext(lines[find(/^const LAKES = /)], ctx);
const { d3, GEO, MARKERS, LAKES } = vm.runInContext("({ d3, GEO, MARKERS, LAKES })", ctx);

// same clean-up as index.html: drop zero-area rings that would fill the whole canvas
const EPS = 1e-7;
const ringArea = (r) => { let a = 0; for (let i = 0; i < r.length - 1; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1]; return Math.abs(a / 2); };
const clean = (g) => {
  if (!g) return null;
  if (g.type === "Polygon") { g.coordinates = g.coordinates.filter((r, i) => i === 0 || ringArea(r) > EPS); return ringArea(g.coordinates[0]) > EPS ? g : null; }
  if (g.type === "MultiPolygon") {
    g.coordinates = g.coordinates.map((p) => p.filter((r, i) => i === 0 || ringArea(r) > EPS)).filter((p) => p.length && ringArea(p[0]) > EPS);
    return g.coordinates.length ? g : null;
  }
  return g;
};
const states = GEO.features.map((f) => { const g = clean(f.geometry); return g ? { ...f, geometry: g } : null; })
  .filter((f) => f && f.properties.name !== "Puerto Rico");

const W = 960, H = 600;
const projection = d3.geoAlbersUsa().scale(1180).translate([W / 2, H / 2]);
const path = d3.geoPath(projection).digits(1);

// same tiny jitter as index.html so basilicas in one city separate identically
const seen = {};
const markers = MARKERS.map((m) => {
  const key = m.lng + "," + m.lat, i = (seen[key] = seen[key] || 0); seen[key]++;
  const p = projection([m.lng, m.lat]);
  if (!p) return null;
  const ang = i * 2.2, rad = i ? 3.0 + i * 1.6 : 0;
  return { id: m.ph, s: m.s, x: +(p[0] + Math.cos(ang) * rad).toFixed(1), y: +(p[1] + Math.sin(ang) * rad).toFixed(1) };
}).filter(Boolean);

// shrink the outlines: relative moves in tenths of a pixel, dropping points under 0.2 px from the last one kept
const n1 = (v) => { const s = (Math.round(v * 10) / 10).toString(); return s.replace(/^(-?)0\./, "$1."); };
function compact(d) {
  if (!d) return "";
  let out = "", px = 0, py = 0, inL = false;
  for (const seg of d.match(/[MLZ][^MLZ]*/g)) {
    const c = seg[0];
    if (c === "Z") { out += "z"; inL = false; continue; }
    const [x, y] = seg.slice(1).split(",").map((v) => Math.round(Number(v) * 10) / 10);
    if (c === "M") { out += "M" + n1(x) + " " + n1(y); px = x; py = y; inL = false; continue; }
    const dx = Math.round((x - px) * 10) / 10, dy = Math.round((y - py) * 10) / 10;
    if (Math.hypot(dx, dy) < 0.2) continue;
    const sx = n1(dx), sy = n1(dy);
    out += (inL ? (sx[0] === "-" ? "" : " ") : "l") + sx + (sy[0] === "-" ? "" : " ") + sy;
    inL = true; px = x; py = y;
  }
  return out;
}

const out = {
  w: W, h: H,
  states: states.map((f) => ({ n: f.properties.name, d: compact(path(f)) })).filter((s) => s.d),
  lakes: LAKES.features.map((f) => compact(path(f))).filter(Boolean).join(""),
  markers,
};
const js = "/* Generated by tools/build_gallery_map.mjs from the map data in index.html. Do not edit by hand. */\n" +
  "window.AB_GMAP = " + JSON.stringify(out) + ";\n";
fs.writeFileSync("members/gallery-map.js", js);
console.log("members/gallery-map.js:", (js.length / 1024).toFixed(0) + " KB,", out.states.length, "states,", markers.length, "markers");
